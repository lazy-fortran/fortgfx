contains

    logical function vk_load_global()
        !! The loader and vkCreateInstance; false when the system has no Vulkan.
        vk_load_global = vk_open_loader()
        if (.not. vk_load_global) return
        call c_f_procpointer(vk_proc(c_null_ptr, "vkCreateInstance"), vkCreateInstance)
    end function vk_load_global

    subroutine vk_load_instance(instance)
        !! Every other function, through the instance (they dispatch to the device).
        type(c_ptr), intent(in) :: instance
        call c_f_procpointer(vk_proc(instance, "vkEnumeratePhysicalDevices"), vkEnumeratePhysicalDevices)
