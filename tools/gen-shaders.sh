#!/bin/sh
# Regenerate src/fortgfx_shaders.f90: the SPIR-V of shaders/*.{vert,frag},
# compiled with glslc (shaderc), as Fortran 32-bit word arrays.
set -eu
top=$(cd "$(dirname "$0")/.." && pwd)
out=$top/src/fortgfx_shaders.f90
tmp=$(mktemp -d "${TMPDIR:-/tmp}/fortgfx-shaders-XXXXXX")
trap 'rm -rf "$tmp"' EXIT
{
    echo "module fortgfx_shaders"
    echo "    !! SPIR-V of shaders/. Generated by tools/gen-shaders.sh with"
    echo "    !! $(glslc --version | head -1 | cut -d' ' -f1-2); do not edit."
    echo "    use iso_fortran_env, only: int32"
    echo "    implicit none"
    echo "    private"
    for s in shape.vert shape.frag textured.vert textured.frag; do
        name=$(echo "$s" | tr . _)
        glslc -O --target-env=vulkan1.3 "$top/shaders/$s" -o "$tmp/$name.spv"
        n=$(( $(wc -c < "$tmp/$name.spv") / 4 ))
        echo "    integer(int32), parameter, public :: ${name}_spv($n) = [ &"
        od -An -v -td4 "$tmp/$name.spv" | tr -s ' \n' '\n' | sed '/^$/d' | awk -v n="$n" '
            { v = $1; if (v == -2147483648) v = "-2147483647 - 1"
              printf "%s%s", (NR % 8 == 1 ? "        " : ""), v
              if (NR < n) printf ", "
              if (NR % 8 == 0 || NR == n) printf " &\n" }'
        echo "        ]"
    done
    echo "end module fortgfx_shaders"
} > "$out"
